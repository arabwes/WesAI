import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const reviewPath = resolve(root, "catalog/operation-review.json");
const outputPath = resolve(root, "src/toast/operation-catalog.generated.ts");
const review = JSON.parse(await readFile(reviewPath, "utf8"));
const httpMethods = new Set(["GET", "POST", "PUT", "PATCH", "DELETE"]);
const ids = new Set();
const errors = [];

for (const operation of review) {
  const key = `${operation.id}:${operation.method}:${operation.path}`;
  if (ids.has(operation.id)) errors.push(`Duplicate operation id ${operation.id}`);
  ids.add(operation.id);
  if (!httpMethods.has(operation.method)) errors.push(`Invalid method on ${key}`);
  if (!operation.requiredScope) errors.push(`Missing scope on ${key}`);
  if (!operation.classification) errors.push(`Unclassified operation ${key}`);
  if (operation.classification === "exposed" && !["GET", "POST"].includes(operation.method)) errors.push(`Mutating operation exposed: ${key}`);
  if (operation.classification === "exposed" && operation.method === "POST" && !operation.reviewedReadOnlyPost) errors.push(`Unreviewed POST exposed: ${key}`);
  if (operation.classification === "excluded" && !operation.exclusionReason) errors.push(`Excluded operation lacks reason: ${key}`);
}
if (errors.length) throw new Error(errors.join("\n"));

const exposed = review.filter((operation) => operation.classification === "exposed");
const source = `// Generated by scripts/build-operation-catalog.mjs. Do not edit by hand.\nimport type { CatalogOperation } from "./operations";\n\nexport const GENERATED_OPERATION_CATALOG = ${JSON.stringify(exposed, null, 2)} as const satisfies readonly CatalogOperation[];\n`;
if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== source) throw new Error("Operation catalog is stale. Run npm run catalog:build after reviewing operation-review.json.");
} else {
  await writeFile(outputPath, source);
  console.log(`Generated ${exposed.length} exposed operations from ${review.length} reviewed candidates.`);
}
