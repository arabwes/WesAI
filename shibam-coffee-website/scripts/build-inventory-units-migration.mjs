// Turns the filled-in docs/inventory-cleanup/inventory-units-worksheet.csv
// into a D1 migration that sets each item's count unit, maximum, and
// walk-order section. Blank cells leave that field unchanged.
//
//   node scripts/build-inventory-units-migration.mjs [worksheet.csv] [output.sql]
//
// Defaults write migrations/0012_inventory_units_and_sections.sql. Review
// the SQL, then apply it with `npm run db:migrate:production`.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const input = resolve(root, process.argv[2] || 'docs/inventory-cleanup/inventory-units-worksheet.csv');
const output = resolve(root, process.argv[3] || 'migrations/0012_inventory_units_and_sections.sql');

// Minimal RFC 4180 parser: quoted fields, doubled quotes, commas, newlines.
export function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < text.length; i += 1) {
    const char = text[i];
    if (quoted) {
      if (char === '"' && text[i + 1] === '"') { field += '"'; i += 1; }
      else if (char === '"') quoted = false;
      else field += char;
    } else if (char === '"') quoted = true;
    else if (char === ',') { row.push(field); field = ''; }
    else if (char === '\n' || char === '\r') {
      if (char === '\r' && text[i + 1] === '\n') i += 1;
      row.push(field); rows.push(row); row = []; field = '';
    } else field += char;
  }
  if (field !== '' || row.length) { row.push(field); rows.push(row); }
  return rows.filter((cells) => cells.some((cell) => cell.trim() !== ''));
}

const sql = (value) => `'${String(value).replace(/'/g, "''")}'`;
const slug = (name) => name.toLowerCase().normalize('NFKD').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 48);

export function buildMigration(csvText) {
  const [header, ...records] = parseCsv(csvText);
  const column = (prefix) => {
    const index = header.findIndex((name) => name.toLowerCase().startsWith(prefix));
    if (index === -1) throw new Error(`Worksheet is missing the "${prefix}" column`);
    return index;
  };
  const col = {
    id: column('catalog_id'), name: column('name'), unit: column('count_unit'), max: column('max_qty'),
    section: column('section'), walk: column('walk_order')
  };

  const problems = [];
  const sections = new Map(); // name → first walk order seen
  const updates = [];
  records.forEach((cells, index) => {
    const line = index + 2;
    const id = cells[col.id].trim();
    const unit = cells[col.unit].trim();
    const maxText = cells[col.max].trim();
    const section = cells[col.section].trim();
    const walkText = cells[col.walk].trim();
    if (!id) { problems.push(`line ${line}: missing catalog_id`); return; }
    const sets = [];
    if (unit) sets.push(`unit = ${sql(unit)}`);
    if (maxText) {
      const max = Number(maxText);
      if (!Number.isFinite(max) || max <= 0) problems.push(`line ${line} (${cells[col.name]}): max_qty "${maxText}" is not a number above 0`);
      else sets.push(`max_qty = ${max}`);
    }
    let walk = null;
    if (walkText) {
      walk = Number(walkText);
      if (!Number.isFinite(walk)) { problems.push(`line ${line} (${cells[col.name]}): walk_order "${walkText}" is not a number`); walk = null; }
      else sets.push(`sort_order = ${Math.round(walk * 10)}`);
    }
    if (section) {
      if (!sections.has(section) || (walk !== null && walk < sections.get(section))) sections.set(section, walk ?? Infinity);
      sets.push(`section_id = (SELECT id FROM inventory_sections WHERE name = ${sql(section)} LIMIT 1)`);
    }
    if (sets.length) updates.push(`UPDATE catalog SET ${sets.join(', ')} WHERE id = ${sql(id)} AND form_type = 'inventory';`);
  });
  if (problems.length) throw new Error(`Fix the worksheet first:\n  ${problems.join('\n  ')}`);

  // Sections come first in walk order: the lowest walk_order of their items.
  const ordered = Array.from(sections.entries()).sort((a, b) => a[1] - b[1] || a[0].localeCompare(b[0]));
  const sectionSql = ordered.map(([name], index) => [
    `INSERT INTO inventory_sections (id, name, sort_order, status, created_at)`,
    `SELECT ${sql(`section-${slug(name) || index + 1}`)}, ${sql(name)}, ${(index + 1) * 10}, 'active', '2026-10-26T00:00:00.000Z'`,
    `WHERE NOT EXISTS (SELECT 1 FROM inventory_sections WHERE name = ${sql(name)});`,
    `UPDATE inventory_sections SET sort_order = ${(index + 1) * 10}, status = 'active' WHERE name = ${sql(name)};`
  ].join('\n'));

  return [
    '-- Generated by scripts/build-inventory-units-migration.mjs from',
    '-- docs/inventory-cleanup/inventory-units-worksheet.csv. Sets each counted',
    "-- item's count unit (how it's bought), per-item maximum, and walk-order section.",
    '',
    ...sectionSql,
    '',
    ...updates,
    '',
    '-- Sections left with no active items (e.g. the interim category-based ones)',
    '-- drop off the count; Management can reactivate them in Admin → Catalog.',
    "UPDATE inventory_sections SET status = 'inactive' WHERE NOT EXISTS (SELECT 1 FROM catalog c",
    "  WHERE c.section_id = inventory_sections.id AND c.form_type = 'inventory' AND c.status != 'discontinued');",
    ''
  ].join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const migration = buildMigration(readFileSync(input, 'utf8'));
  writeFileSync(output, migration);
  console.log(`Wrote ${output}`);
}
